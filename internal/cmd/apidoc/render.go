package main

import (
	"bytes"
	"fmt"
	"regexp"
	"strings"
	"unicode"
)

const header = "Code generated by go run ./internal/cmd/apidoc; DO NOT EDIT."

// sizeType is the TypeScript type of Size, which is parsed by
// internal/data.ParseSizer rather than decoded into a struct.
const sizeType = `number
  | string
  | { dist: "uniform"; min: number | string; max: number | string }
  | { dist: "lognormal"; median: number | string; sigma: number }
  | { dist: "choice"; values: { size: number | string; weight: number }[] }`

const sizeDoc = "A size: a number of bytes, a string with a binary unit such as `\"1MiB\"`, or a size distribution.\nSee the Sizes section of README."

// readmeSection matches a reference to a README section in doc comments.
var readmeSection = regexp.MustCompile(`the\s+([A-Za-z][A-Za-z\s]*?)\s+section\s+of\s+README`)

// readmeLinks links the references to README sections.
func readmeLinks(doc string) string {
	return readmeSection.ReplaceAllStringFunc(doc, func(m string) string {
		name := strings.Join(strings.Fields(readmeSection.FindStringSubmatch(m)[1]), " ")
		return fmt.Sprintf("[%s](../README.md#%s) in README", name, anchor(name))
	})
}

func markdown(a *api) []byte {
	var b bytes.Buffer
	w := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }
	doc := readmeLinks

	w("<!-- %s -->\n\n", header)
	w("# API reference\n\n")
	w("The JavaScript API of the `k6/x/s3` module. TypeScript declarations are in [index.d.ts](../index.d.ts).\n\n")
	w("```js\nimport s3 from \"k6/x/s3\";\n```\n\n")

	runID := "`s3.runId()`"
	ctor := "`new s3.Client(config)`"
	w("- [%s](#%s)\n", runID, anchor(runID))
	w("- [%s](#%s)\n", ctor, anchor(ctor))
	for _, m := range a.methods {
		h := methodHeading(m)
		w("  - [%s](#%s)\n", h, anchor(h))
	}
	w("- [Types](#types)\n")
	for _, t := range a.types {
		w("  - [`%s`](#%s)\n", t.name, anchor(t.name))
	}
	w("  - [`Size`](#size)\n\n")

	w("## %s\n\n", runID)
	w("```ts\nrunId(): %s\n```\n\n%s\n\n", a.runID.returns, doc(a.runID.doc))

	w("## %s\n\n", ctor)
	w("```ts\nnew Client(config: ClientConfig): Client\n```\n\n%s\n\n", doc(a.clientDoc))
	for _, m := range a.methods {
		w("### %s\n\n", methodHeading(m))
		w("```ts\n%s\n```\n\n%s\n\n", signature(m), doc(m.doc))
		if m.options != nil {
			w("Options: [`%s`](#%s)\n\n", m.options.name, anchor(m.options.name))
		}
	}

	w("## Types\n\n")
	for _, t := range a.types {
		w("### `%s`\n\n%s\n\n", t.name, doc(t.doc))
		if t.options {
			w("| Key | Type | Default | Description |\n| --- | --- | --- | --- |\n")
		} else {
			w("| Field | Type | Description |\n| --- | --- | --- |\n")
		}
		for _, f := range t.fields {
			typ := "`" + strings.ReplaceAll(f.typ, "|", `\|`) + "`"
			if isType(a, f.typ) {
				typ = fmt.Sprintf("[`%s`](#%s)", f.typ, anchor(f.typ))
			}
			desc := cell(doc(strings.TrimSpace(f.doc + " " + f.note)))
			if t.options {
				w("| `%s` | %s | %s | %s |\n", f.name, typ, cell(f.def), desc)
			} else {
				w("| `%s` | %s | %s |\n", f.name, typ, desc)
			}
		}
		w("\n")
	}
	w("### `Size`\n\n%s\n\n```ts\ntype Size =\n  | %s;\n```\n", doc(sizeDoc), sizeType)
	return b.Bytes()
}

func typescript(a *api) []byte {
	var b bytes.Buffer
	w := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }

	w("// %s\n\n", header)
	w("/**\n * TypeScript declarations of the k6/x/s3 module. See docs/api.md for the details.\n */\n")
	w("declare module \"k6/x/s3\" {\n")
	jsdoc(&b, "  ", a.runID.doc)
	w("  export function %s;\n\n", signature(a.runID))

	jsdoc(&b, "  ", a.clientDoc)
	w("  export class Client {\n")
	w("    constructor(config: ClientConfig);\n")
	for _, m := range a.methods {
		w("\n")
		jsdoc(&b, "    ", m.doc)
		w("    %s;\n", signature(m))
	}
	w("  }\n")

	for _, t := range a.types {
		w("\n")
		jsdoc(&b, "  ", t.doc)
		w("  export interface %s {\n", t.name)
		for i, f := range t.fields {
			if i > 0 {
				w("\n")
			}
			doc := strings.TrimSpace(f.doc + "\n\n" + f.note)
			if f.def != "" {
				doc += "\n\nDefault: " + f.def
			}
			jsdoc(&b, "    ", doc)
			opt := ""
			if t.options {
				opt = "?"
			}
			w("    %s%s: %s;\n", f.name, opt, f.typ)
		}
		w("  }\n")
	}

	w("\n")
	jsdoc(&b, "  ", sizeDoc)
	w("  export type Size =\n    | %s;\n\n", strings.ReplaceAll(sizeType, "\n", "\n  "))
	w("  const s3: { runId: typeof runId; Client: typeof Client };\n")
	w("  export default s3;\n")
	w("}\n")
	return b.Bytes()
}

func methodHeading(m method) string {
	names := make([]string, len(m.params))
	for i, p := range m.params {
		names[i] = p.name
		if p.optional {
			names[i] += "?"
		}
	}
	return fmt.Sprintf("`client.%s(%s)`", m.name, strings.Join(names, ", "))
}

func signature(m method) string {
	params := make([]string, len(m.params))
	for i, p := range m.params {
		opt := ""
		if p.optional {
			opt = "?"
		}
		params[i] = fmt.Sprintf("%s%s: %s", p.name, opt, p.typ)
	}
	return fmt.Sprintf("%s(%s): %s", m.name, strings.Join(params, ", "), m.returns)
}

func jsdoc(b *bytes.Buffer, indent, doc string) {
	doc = strings.ReplaceAll(doc, "*/", `*\/`)
	fmt.Fprintf(b, "%s/**\n", indent)
	for line := range strings.SplitSeq(doc, "\n") {
		fmt.Fprintf(b, "%s\n", strings.TrimRight(indent+" * "+line, " "))
	}
	fmt.Fprintf(b, "%s */\n", indent)
}

func isType(a *api, name string) bool {
	for _, t := range a.types {
		if t.name == name {
			return true
		}
	}
	return false
}

// cell formats text for a Markdown table cell.
func cell(s string) string {
	return strings.ReplaceAll(strings.Join(strings.Fields(s), " "), "|", `\|`)
}

// anchor returns the GitHub anchor of a heading.
func anchor(heading string) string {
	var b strings.Builder
	for _, r := range strings.ToLower(heading) {
		switch {
		case unicode.IsLetter(r) || unicode.IsDigit(r) || r == '-' || r == '_':
			b.WriteRune(r)
		case r == ' ':
			b.WriteRune('-')
		}
	}
	return b.String()
}
